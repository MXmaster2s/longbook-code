import PackageDescription

let package = Package(
    name: "LongbookCore",
    platforms: [.iOS(.v17), .macOS(.v14)],
    products: [
        .library(name: "LongbookCore", targets: ["LongbookCore"]),
    ],
    dependencies: [
        .package(url: "https://github.com/supabase/supabase-swift.git", from: "2.0.0"),
        // MIT, with MIT dependencies — reads the .xlsx statements banks hand out.
        .package(url: "https://github.com/CoreOffice/CoreXLSX.git", exact: "0.14.2"),
    ],
    targets: [
        .target(
            name: "LongbookCore",
            dependencies: [
                .product(name: "Supabase", package: "supabase-swift"),
                .product(name: "CoreXLSX", package: "CoreXLSX"),
            ],
            // .process, not .copy: copying keeps a Resources folder inside the bundle, and
            // codesign reads that layout as an old-style bundle and refuses to sign it.
            resources: [.process("Resources")]
        ),
        .testTarget(
            name: "LongbookCoreTests",
            dependencies: ["LongbookCore"],
            // The statement shapes a bank hands out, generated by
            // scripts/gen-statement-fixtures.mts — the same bytes the server's proof reads.
            resources: [.copy("Fixtures")]
        ),
    ]
)
